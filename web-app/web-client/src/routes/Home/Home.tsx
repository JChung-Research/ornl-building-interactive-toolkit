const groupRoomsByFloor = (rooms: Room[]) => {
  const floorMap = new Map<string, Room[]>();
  rooms.forEach((r) => {
    const key = r.floor ?? "Unknown";
    const arr = floorMap.get(key) ?? [];
    arr.push(r);
    floorMap.set(key, arr);
  });

  const entries = Array.from(floorMap.entries());

  const floorSortKey = (floor: string): number | string => {
    const n = Number(floor);
    return Number.isFinite(n) ? n : floor;
  };

  entries.sort((a, b) => {
    const ak = floorSortKey(a[0]);
    const bk = floorSortKey(b[0]);

    if (typeof ak === "number" && typeof bk === "number") return ak - bk;
    return String(ak).localeCompare(String(bk), undefined, { numeric: true });
  });

  return entries;
};

